"""One rights/risk decision for every video and music source, before editing and before publication.

ACCEPTED means: a recorded permission with evidence, a licence allowing modification and
redistribution (or an explicit commercial grant), a fresh official availability check for
YouTube-origin media, and no known claim, rightsholder or geo signal. It is NOT a Content ID
clearance: YouTube Studio's check of the final file stays mandatory before any publication.
REJECTED means a concrete negative signal. UNVERIFIED means reuse cannot be established.
"""
from __future__ import annotations

import json
import os
import re
import time
from datetime import datetime, timezone
from pathlib import Path

from . import catalogue as cat
from .media import UltraError
from .spec import normalize
from .youtube_preflight import VIDEO_ID, lookup, youtube_id

ACCEPTED, REJECTED, UNVERIFIED = "ACCEPTED", "REJECTED", "UNVERIFIED"
CLAIMS_FILE = Path.home() / ".local/share/youtube-edit-ultra/excluded_media.json"
REPORT_NAME = "rights_gate_report.json"

# Owners whose broadcast footage YouTube claims or blocks (worldwide for UEFA, FIFA, LFP on
# 2026-11 uploads; by territory for LaLiga). A match means "rightsholder material", not "safe".
# Competition names are matched in the uploader and the title (fan re-uploads of broadcasts);
# broadcaster names and short acronyms only in the uploader, where they are unambiguous.
_COMPETITIONS = [
    r"uefa", r"ucl", r"champions league", r"europa league", r"conference league", r"euro 20\d\d", r"fifa",
    r"world cup", r"coupe du monde", r"copa del mundo", r"copa america", r"ligue 1",
    r"ligue de football professionnel", r"premier league", r"laliga", r"la liga", r"serie a",
    r"bundesliga", r"liga portugal", r"eredivisie", r"ufc", r"wwe", r"formula 1", r"world feed",
]
_BROADCASTERS = [
    r"lfp", r"mls", r"nba", r"nfl", r"nhl", r"mlb", r"f1", r"bein sports?", r"canal\+?",
    r"dazn", r"sky sports?", r"bt sport", r"tnt sports", r"espn", r"rmc sport", r"eurosport",
    r"movistar", r"sport ?tv", r"fox sports", r"nbc sports", r"cbs sports", r"tf1", r"m6",
    r"france ?tv", r"rtp", r"sic", r"tvi", r"top rank", r"matchroom", r"showtime", r"hbo boxing",
    r"premier boxing champions", r"pbc",
]
COMPETITIONS = re.compile(r"\b(" + "|".join(_COMPETITIONS) + r")\b")
BROADCASTERS = re.compile(r"\b(" + "|".join(_BROADCASTERS) + r")(?:\b|$)")
# Signals of label-distributed recordings, which Content ID usually matches.
COMMERCIAL_MUSIC = re.compile(r"(vevo|provided to youtube by|auto generated by youtube)\b")


def _words(value) -> str:
    """Lowercase words: 'UCL_Final_World_Feed' -> 'ucl final world feed' ('+' kept for Canal+)."""
    return " ".join(re.split(r"[^a-z0-9+]+", normalize(str(value or "")))).strip()


def licence_terms(value) -> dict | None:
    """Map a licence URL or label to SPDX-like terms; None when it cannot be identified."""
    text = normalize(str(value or "")).strip()
    if not text:
        return None
    url = re.search(r"creativecommons\.org/(licenses|publicdomain)/([a-z+-]+)(?:/([0-9.]+))?", text)
    if url:
        kind, name, version = url.groups()
        if kind == "publicdomain":
            spdx = {"zero": "CC0-1.0", "mark": "PDM"}.get(name)
            return dict(spdx=spdx, modification=True, redistribution=True, commercial=True) if spdx else None
        parts = name.split("-")
        if parts[0] != "by" or not set(parts) <= {"by", "nc", "nd", "sa"}:
            return None
        spdx = "CC-" + "-".join(p.upper() for p in parts) + (f"-{version}" if version else "")
    elif text.startswith("creative commons attribution license"):
        spdx, parts = "CC-BY-3.0", ["by"]  # YouTube's only CC option
    elif text in {"cc0", "cc0 1.0", "cc0-1.0"}:
        return dict(spdx="CC0-1.0", modification=True, redistribution=True, commercial=True)
    elif text in {"public domain", "pdm"}:
        return dict(spdx="PDM", modification=True, redistribution=True, commercial=True)
    elif text.startswith("standard youtube license"):
        return dict(spdx="LicenseRef-YouTube-Standard", modification=False, redistribution=False,
                    commercial=False)
    elif "mixkit.co/license" in text and "musicfree" in text:
        # Free inside a larger work, never standalone redistribution of the track.
        return dict(spdx="LicenseRef-Mixkit-Music-Free", modification=True, redistribution=True,
                    commercial=True)
    else:
        label = re.fullmatch(r"(?:cc[ -])?(by(?:[ -](?:nc|nd|sa))*)(?:[ -]([0-9.]+))?", text)
        if not label:
            return None
        parts = re.split(r"[ -]", label.group(1))
        spdx = "CC-" + "-".join(p.upper() for p in parts) + (f"-{label.group(2)}" if label.group(2) else "")
    return dict(spdx=spdx, modification="nd" not in parts, redistribution=True,
                commercial="nc" not in parts)


def load_claims(path: Path | None = None) -> list[dict]:
    """Claims read in YouTube Studio on earlier uploads: [{id|sha256, reason, window?, claim?}]."""
    path = Path(os.environ.get("YEU_CLAIMS_FILE") or CLAIMS_FILE) if path is None else Path(path)
    if not path.is_file():
        return []
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise UltraError(f"Registre des revendications illisible : {path}") from exc
    if not isinstance(rows, list):
        raise UltraError(f"Registre des revendications invalide (liste attendue) : {path}")
    out = []
    for row in rows:
        if not isinstance(row, dict):
            raise UltraError(f"Registre des revendications invalide : {row!r} ({path})")
        vid = str(row.get("id") or "").strip()
        vid = youtube_id(vid) or vid
        digest = str(row.get("sha256") or "").strip().lower()
        if (vid and not VIDEO_ID.fullmatch(vid)) or (digest and not re.fullmatch(r"[0-9a-f]{64}", digest)) \
                or not (vid or digest):
            # A row that can never match would silently re-admit a claimed source.
            raise UltraError(f"Revendication sans id YouTube ou sha256 valide : {row!r} ({path})")
        out.append(dict(row, id=vid or None, sha256=digest or None))
    return out


def _sidecar(path: Path) -> dict:
    try:
        data = json.loads(path.with_suffix(".info.json").read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def describe(path, kind: str, *, state: dict | None = None, provenance: str | None = None) -> dict:
    """Collect identity and provenance of one media file from the catalogue and its yt-dlp sidecar."""
    path = Path(path).expanduser().resolve()
    state = state or {}
    row = state.get("media", {}).get(str(path)) or {}
    sidecar = _sidecar(path)
    digest = row.get("sha256") if row and cat.current_content(dict(row)) else None
    if digest is None and path.is_file():
        digest = cat.sha256(path)
    # A copy, hardlink or case variant inherits the grant by hash: it must inherit its identity too,
    # even when the copy has its own catalogue row without URL or sidecar.
    twins = [r for r in state.get("media", {}).values()
             if isinstance(r, dict) and digest and r.get("sha256") == digest]
    if not row or row.get("sha256") != digest:
        row = twins[0] if twins else {}
    for twin in twins:
        if not sidecar:
            sidecar = _sidecar(Path(twin.get("path", "")))
        for key in ("url", "uploader", "title", "license"):
            if twin.get(key) and not row.get(key):
                row = dict(row, **{key: twin[key]})
    evidence = (state.get("permissions", {}).get(digest) or {}).get("evidence")
    evidence = evidence if isinstance(evidence, dict) else {}
    for key, value in (("webpage_url", evidence.get("webpage_url") or evidence.get("url")),
                       ("uploader", evidence.get("uploader")), ("channel_url", evidence.get("channel_url")),
                       ("title", evidence.get("title"))):
        if value and not sidecar.get(key):
            sidecar[key] = value
    url = row.get("url") or sidecar.get("webpage_url") or sidecar.get("original_url")
    # Every place that names these bytes' origin; two different YouTube videos is a contradiction.
    candidates = [row.get("url"), sidecar.get("webpage_url"), sidecar.get("original_url"),
                  evidence.get("webpage_url"), evidence.get("url"), *(t.get("url") for t in twins)]
    ids = [youtube_id(u) for u in candidates if isinstance(u, str)]
    if str(sidecar.get("extractor_key", "")).lower() == "youtube" and VIDEO_ID.fullmatch(str(sidecar.get("id", ""))):
        ids.append(sidecar["id"])
    ids = list(dict.fromkeys(i for i in ids if i))
    vid = (youtube_id(url) if url else None) or (ids[0] if ids else None)
    meta = {k: sidecar.get(k) for k in ("title", "uploader", "channel", "channel_url", "license",
                                         "availability", "artist", "album", "track", "extractor_key")}
    meta["description"] = str(sidecar.get("description") or "")[:3000]
    for key in ("title", "uploader", "license", "artist", "isrc", "spotify_uri"):
        if row.get(key) and not meta.get(key):
            meta[key] = row[key]
    return dict(path=str(path), kind=kind, exists=path.is_file(), sha256=digest, url=url,
                youtube_id=vid, youtube_ids=ids,
                provenance=provenance or ("downloaded_url" if url else "local_file"),
                has_sidecar=bool(sidecar), metadata=meta)


def _hints(source: dict) -> dict:
    meta = source["metadata"]
    owner = _words(" ".join(str(meta.get(k) or "") for k in ("uploader", "channel", "channel_url")))
    title = _words(meta.get("title"))
    sports = sorted({m.group(1) for m in COMPETITIONS.finditer(owner + " | " + title)}
                    | {m.group(1) for m in BROADCASTERS.finditer(owner)})
    music_text = owner + " " + _words(str(meta.get("description") or "")[:400])
    commercial = sorted({m.group(1) for m in COMMERCIAL_MUSIC.finditer(music_text)})
    if any(re.search(r"\btopic$", _words(meta.get(k))) for k in ("uploader", "channel")):
        commercial.append("topic channel")
    for key in ("isrc", "spotify_uri"):
        if meta.get(key):
            commercial.append(key)
    if str(meta.get("extractor_key") or "").lower() == "youtube" and meta.get("track") and (
            meta.get("artist") or meta.get("album")):
        commercial.append("youtube music metadata")  # 'Music in this video' credits a label release
    return dict(sports_rightsholder=sports, commercial_music=commercial)


EVIDENCE_URL_KEYS = ("webpage_url", "url", "source_url", "foreign_landing_url", "original_url")


def _evidence_url(grant: dict) -> bool:
    """A declared licence counts only with the page where it was read."""
    evidence = grant.get("evidence")
    return isinstance(evidence, dict) and any(
        isinstance(evidence.get(k), str) and evidence[k].startswith("https://") for k in EVIDENCE_URL_KEYS)


def _grant_terms(grant: dict) -> dict | None:
    evidence = grant.get("evidence")
    for value in (grant.get("license"),
                  evidence.get("license") if isinstance(evidence, dict) else None):
        terms = licence_terms(value)
        if terms:
            return terms
    return None


def assess(source: dict, *, grant: dict | None = None, claims=(), youtube: dict | None = None,
           checked_at: str | None = None) -> dict:
    """Decide ACCEPTED / REJECTED / UNVERIFIED for one described source."""
    grant = grant or {}
    reject, unverified, basis = [], [], []
    commercial_grant = cat.grant_allows(grant, "commercial")
    personal_grant = cat.grant_allows(grant, "personal")
    if not source.get("exists"):
        reject.append("SOURCE_FILE_MISSING")
    ids = set(source.get("youtube_ids") or ([source["youtube_id"]] if source.get("youtube_id") else []))
    hits = [c for c in claims if (c.get("id") and c["id"] in ids)
            or (c.get("sha256") and c["sha256"] == source.get("sha256"))]
    if hits:
        reject.append("PREVIOUS_CONTENT_ID_CLAIM")
        basis.append("claim_registry")
    if len(ids) > 1:
        unverified.append("PROVENANCE_CONFLICT")
    availability = source["metadata"].get("availability")
    if availability not in (None, "public"):
        # yt-dlp saw it private, members-only, paid or login-gated when it was fetched.
        reject.append(f"SOURCE_AVAILABILITY_{str(availability).upper()}")
    grant_terms = _grant_terms(grant)
    declared = [t for t in (grant_terms, licence_terms(source["metadata"].get("license"))) if t]
    terms = declared[0] if declared else None
    geo = None
    if source.get("youtube_id"):
        if youtube is None:
            unverified.append("YOUTUBE_STATUS_NOT_RECHECKED")
        elif youtube["status"] == "UNKNOWN":
            unverified.extend(youtube["reasons"])
        else:
            basis.append("youtube_data_api")
            geo = youtube.get("region_restriction")
            for reason in youtube["reasons"]:
                if reason == "NO_CREATIVE_COMMONS_LICENSE":
                    if not commercial_grant and any(
                            t["spdx"] != "LicenseRef-YouTube-Standard" for t in declared):
                        reject.append("LICENCE_CONTRADICTED_BY_YOUTUBE")
                    declared.append(licence_terms("standard youtube license"))
                    terms = terms or declared[-1]
                elif reason == "SOURCE_UNAVAILABLE_OR_NOT_PUBLIC":
                    reject.append("SOURCE_REMOVED_OR_PRIVATE")
                elif reason.endswith("_UNVERIFIED"):
                    unverified.append(reason)
                else:
                    reject.append(reason)
            if youtube.get("license") == "creativeCommon" and terms is None:
                terms = licence_terms("creative commons attribution license")
                declared.append(terms)
    hints = _hints(source)
    if hints["sports_rightsholder"] and not commercial_grant:
        reject.append("SPORTS_RIGHTSHOLDER_FOOTAGE")
    if source["kind"] == "audio" and hints["commercial_music"] and not commercial_grant:
        reject.append("COMMERCIAL_MUSIC_WITHOUT_LICENCE")
    if declared and not commercial_grant:
        # The most restrictive declaration wins: a grant cannot erase the source's own NC/ND.
        if not all(t["modification"] for t in declared):
            reject.append("LICENCE_FORBIDS_MODIFICATION")
        if not all(t["redistribution"] for t in declared):
            reject.append("LICENCE_FORBIDS_REDISTRIBUTION")
        if not all(t["commercial"] for t in declared):
            # YouTube places ads on any video, so NC material is refused for publication.
            reject.append("NON_COMMERCIAL_LICENCE")
    if commercial_grant:
        basis.append("documented_commercial_grant")
        reliability = "documented_licence"
    elif personal_grant and grant.get("basis") == "user_attested_not_independently_verified":
        unverified.append("USER_ATTESTATION_ONLY")
        reliability = "user_attestation"
    elif personal_grant:
        basis.append("recorded_grant")
        trusted = grant.get("basis") == "CC_BY_from_user_trusted_publisher"
        if terms is None:
            unverified.append("LICENCE_UNKNOWN")
        elif grant_terms is None and not trusted:
            # The uploader's own CC label proves nothing about who owns the footage.
            unverified.append("LICENCE_ONLY_DECLARED_BY_SOURCE")
        elif grant_terms is not None and not (trusted or _evidence_url(grant)):
            unverified.append("LICENCE_WITHOUT_SOURCE_EVIDENCE")
        reliability = "declared_licence" if terms else "unlicensed_grant"
    else:
        unverified.append("NO_RECORDED_PERMISSION" if source.get("url") or source.get("has_sidecar")
                          else "LOCAL_FILE_WITHOUT_PROVENANCE")
        reliability = "none"
    decision = REJECTED if reject else UNVERIFIED if unverified else ACCEPTED
    return dict(
        source_id=source.get("youtube_id") or source.get("sha256") or source["path"],
        kind=source["kind"], path=source["path"], sha256=source.get("sha256"), url=source.get("url"),
        youtube_id=source.get("youtube_id"), provenance=source["provenance"],
        licence=dict(spdx=terms["spdx"] if terms else None,
                     evidence=grant.get("evidence") if grant else None,
                     reviewer=grant.get("rights_verified_by"), credit=grant.get("credit")),
        modification_allowed=bool(commercial_grant and grant.get("adaptation")) or (
            terms["modification"] if terms else None),
        redistribution_allowed=bool(commercial_grant and grant.get("distribution")) or (
            terms["redistribution"] if terms else None),
        geo_restriction=geo, claim_hints=dict(hints, previous_claims=[c.get("reason") for c in hits]),
        checked_at=checked_at or datetime.now(timezone.utc).isoformat(timespec="seconds"),
        reliability=reliability, evidence_basis=basis, decision=decision,
        reasons=list(dict.fromkeys(reject + unverified)),
    )


def gate(sources, *, state: dict | None = None, claims=None, api_key: str | None = None,
         offline: bool = False) -> list[dict]:
    """Assess (path, kind, provenance) items with one batched YouTube call; fails closed offline."""
    registry_error = None
    if claims is None:
        try:
            claims = load_claims()
        except UltraError as exc:
            # Never abort a personal edit, never let it look publishable either.
            claims, registry_error = [], str(exc)
    state = state or {}
    described = [describe(path, kind, state=state, provenance=provenance)
                 for path, kind, provenance in sources]
    ids = [s["youtube_id"] for s in described if s["youtube_id"]]
    statuses = {} if offline or not ids else lookup(ids, api_key=api_key)
    if offline:
        statuses = {i: dict(status="UNKNOWN", reasons=["OFFLINE_NOT_RECHECKED"], video_id=i) for i in ids}
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    records = [assess(s, grant=state.get("permissions", {}).get(s["sha256"]), claims=claims,
                      youtube=statuses.get(s["youtube_id"]), checked_at=stamp) for s in described]
    if registry_error:
        for record in records:
            record["reasons"].append("CLAIM_REGISTRY_UNREADABLE")
            record["claim_registry_error"] = registry_error
            if record["decision"] == ACCEPTED:
                record["decision"] = UNVERIFIED
    return records


def summary(records: list[dict]) -> dict:
    counts = {d: sum(r["decision"] == d for r in records) for d in (ACCEPTED, REJECTED, UNVERIFIED)}
    return dict(counts=counts, publishable=bool(records) and counts[ACCEPTED] == len(records),
                not_accepted=[dict(path=r["path"], kind=r["kind"], decision=r["decision"],
                                   reasons=r["reasons"]) for r in records if r["decision"] != ACCEPTED])


def write_report(folder, records: list[dict], **context) -> dict:
    report = dict(
        records=records, summary=summary(records), generated_at=time.time(), **context,
        scope=("Source metadata, licences and recorded claims only. Not a Content ID clearance: "
               "upload privately, read YouTube Studio checks, then decide publication."))
    cat.save(Path(folder) / REPORT_NAME, report)
    return report


def bind_montage(folder, montage_sha256: str) -> None:
    """Tie the report to the exact rendered file, so it cannot vouch for another upload."""
    path = Path(folder) / REPORT_NAME
    report = cat.read(path, None)
    if isinstance(report, dict):
        report["montage_sha256"] = montage_sha256
        cat.save(path, report)


def assert_publishable(records: list[dict]) -> None:
    rows = summary(records)["not_accepted"]
    if rows:
        shown = "; ".join(f"{Path(r['path']).name}: {r['decision']} ({', '.join(r['reasons'][:3])})"
                          for r in rows[:5])
        raise UltraError(f"{len(rows)} source(s) non publiable(s) : {shown}")
